#include "libft.h"

int	ft_strncmp(char *s1, char *s2, size_t n)
{
	size_t	i;

	i = 0;
	if (n == 0)
		return (0);
	if (i < n && s1[i] && s1[i] == s2[i])
	{
		while (s1[i] == s2[i])
			i++;
	}
	return (s1[i] - s2[i]);
}
